// Writes docs/laws.md: every law `bun run laws` proves, by area, from the
// same laws/<area>.ts entries the runner loads, so the page cannot drift
// from what is proven.
//
//   bun scripts/laws-doc.ts           write docs/laws.md
//   bun scripts/laws-doc.ts --check   exit 1 if docs/laws.md is stale
//
// It lists the laws without proving them (that is `bun run laws`, about
// 20 s); the rows it names are exactly the rows the runner prints.

import {readdirSync, readFileSync, writeFileSync} from 'node:fs'
import {join} from 'node:path'
import type {Entry} from '../laws/kit.ts'

const repo = join(import.meta.dir, '..')
const lawsDir = join(repo, 'laws')
const target = join(repo, 'docs', 'laws.md')

// The same discovery as laws/run.ts.
async function entries(): Promise<Entry[]> {
  const files = readdirSync(lawsDir).filter((f) => f.endsWith('.ts') && !['kit.ts', 'run.ts'].includes(f)).sort()
  const all: Entry[] = []
  for (const f of files) all.push(...((await import(join(lawsDir, f))).entries as Entry[]))
  return all
}

const INTRO = `# Laws

<!-- Generated by scripts/laws-doc.ts from laws/*.ts; edit those, then run \`bun run laws:doc\`. -->

jev-fabric's policy is split the way 0.8.1's Bend was: **pure modules**
(\`src/*/core.ts\`, \`*-core.ts\` and the codec) decide, and **drivers** do the
IO (files, processes, clocks, sockets, \`bun:ffi\` in \`src/sys/\`). A pure
module imports nothing that does IO, so its rules can be stated and proven
apart from the system.

Each rule below is written as a [gdp-wired](https://github.com/monotykamary/gdp-wired)
rule and proven three ways by \`bun run laws\`:

- **laws**: proven by gdp-wired's kernel with no proof written by hand
  (\`proveSteps\` for a rule's every step, from its start or, where marked,
  from any state its laws allow; \`proveDecision\` for a single function);
- **bugs refused**: a broken variant of the same rule, the bug the laws are
  there to rule out, must fail the same laws;
- **held to the real code**: the rule runs beside the TypeScript that ships
  (\`src/\`), on random or every input, and must agree step for step.

\`bun run laws\` prints one row per item below and ends with \`ALL LAWS PROVEN\`
only when every row holds. CI runs it on every push.

## What this does not prove

This is scoped proof of the pure core, not whole-program verification. The
laws say what the policy decides; a rule held to the code is a test of
agreement on the inputs tried, not a proof that the two are equal. Outside
the laws, and covered by unit and conformance tests instead:

- the drivers: process groups, signals, deadlines that kill a group, file
  locks and leases, spools on disk, the store, \`serve\`'s concurrency;
- that a clock advances, that a system call returns, or that a receipt
  describes what really happened to a process;
- Bun, its \`fetch\` and TLS, libc, the OS, the filesystem and the CA store,
  which remain trusted;
- Jev's judgment and whether a task is really done;
- programs run with \`jev-fabric -- run\`: they are trusted code, not a
  sandbox, and nothing here is claimed for them.

A deadline budget is not an isolated resource group, and timing (scheduler
or launch latency) is not a hard real-time guarantee.
`

const ruleOf = (e: Entry) => e.rule?.name ?? e.decisions?.[0]?.rule.name ?? '?'

function render(all: Entry[]): string {
  const areas: string[] = []
  const byArea = new Map<string, Entry[]>()
  for (const e of all) {
    if (!byArea.has(e.area)) {
      byArea.set(e.area, [])
      areas.push(e.area)
    }
    byArea.get(e.area)!.push(e)
  }
  let laws = 0
  let broken = 0
  let held = 0
  const body: string[] = []
  for (const area of areas) {
    body.push(`## ${area}`, '')
    for (const e of byArea.get(area)!) {
      const name = ruleOf(e)
      if (e.rule) {
        const stated = [...(e.laws ?? []), ...(e.steps ?? [])]
        laws += stated.length
        body.push(`Rule \`${name}\` (\`proveSteps\`${e.from ? ', from any state' : ''}):`, '')
        for (const l of stated) body.push(`- ${l.name}`)
        body.push('')
      }
      if (e.decisions?.length) {
        laws += e.decisions.length
        for (const d of e.decisions) body.push(`- ${d.name} (\`${d.rule.name}\`, \`proveDecision\`)`)
        body.push('')
      }
      if (e.broken.length) {
        broken += e.broken.length
        body.push(`Bugs refused (on the broken \`${name}\`):`, '')
        for (const b of e.broken) body.push(`- ${b.what}`)
        body.push('')
      }
      if (e.held.length) {
        held += e.held.length
        body.push(`Held to the real code (\`${name}\`):`, '')
        for (const h of e.held) body.push(`- ${h.against}${h.exhaustive ? ' (every case)' : ''}`)
        body.push('')
      }
    }
  }
  const total = laws + broken + held
  const summary = `${total} rows over ${areas.length} areas: ${laws} laws, ${broken} bugs refused, ${held} comparisons with the real code.`
  return `${INTRO}\n${summary}\n\n${body.join('\n').trimEnd()}\n`
}

const text = render(await entries())
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {}
  if (current !== text) {
    console.error('docs/laws.md is stale: run `bun run laws:doc`')
    process.exit(1)
  }
  console.log('docs/laws.md is current')
} else {
  writeFileSync(target, text)
  console.log(`wrote docs/laws.md`)
}
